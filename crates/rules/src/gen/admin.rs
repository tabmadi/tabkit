//! `gen/admin`: Lowdefy admin pages from the OpenAPI specs. A tag with `x-admin: crud` becomes list, add, and edit
//! pages, and an operation with `x-admin: action` becomes one form.

use std::collections::BTreeMap;

use anyhow::{Context, Result};
use saphyr::MarkedYaml;

use super::Output;
use super::emit::{self, Node, map};
use tabkit_core::config::{Config, Paths};
use tabkit_core::repo::Repo;
use tabkit_core::yaml;

const ID: &str = "gen/admin";
const DEFAULT_HEADER: &str = "# Generated by tabkit. Do not edit.\n";
const PAGE: &str = "PageSiderMenu";
const AXIOS: &str = "AxiosHttp";
const METHODS: [&str; 8] = [
    "get", "put", "post", "delete", "patch", "options", "head", "trace",
];
const LIST_PAGE_SIZE: i64 = 20;

/// The directory that this generator owns, so a page of a removed operation goes away.
pub fn owned(cfg: &Config) -> Result<Option<String>> {
    cfg.option_str(ID, "out-dir")
}

#[derive(Clone, Default)]
struct Prop {
    name: String,
    kind: String,
    reference: String,
}

impl Prop {
    fn is_money(&self) -> bool {
        self.reference.rsplit('/').next() == Some("Money") && !self.reference.is_empty()
    }
}

#[derive(Clone)]
struct Op<'a> {
    id: String,
    admin: String,
    tags: Vec<String>,
    path_params: Vec<String>,
    body: Option<&'a MarkedYaml<'a>>,
    response: Option<&'a MarkedYaml<'a>>,
    has_201: bool,
    method: String,
    path: String,
}

impl Op<'_> {
    fn segments(&self) -> usize {
        self.path.split('/').filter(|s| !s.is_empty()).count()
    }
}

#[derive(Default)]
struct Resource<'a> {
    name: String,
    list: Option<Op<'a>>,
    get: Option<Op<'a>>,
    create: Option<Op<'a>>,
    update: Option<Op<'a>>,
    remove: Option<Op<'a>>,
}

impl<'a> Resource<'a> {
    /// An async create, a POST that returns 202, starts a workflow and stays unassigned.
    fn classify(&mut self, op: Op<'a>) {
        let two = op.segments() == 2;
        match op.method.as_str() {
            "get" if op.path_params.is_empty() => self.list = Some(op),
            "get" if two => self.get = Some(op),
            "post" if op.path_params.is_empty() && op.has_201 => self.create = Some(op),
            "put" if two => self.update = Some(op),
            "delete" if two => self.remove = Some(op),
            _ => {}
        }
    }
}

struct Doc<'a> {
    schemas: BTreeMap<String, &'a MarkedYaml<'a>>,
}

struct Writer {
    root: String,
    header: String,
    out: Vec<Output>,
}

impl Writer {
    fn write(&mut self, relative: &str, node: &Node) {
        let mut text = self.header.clone();
        text.push_str(&emit::to_string(node));
        self.out.push(Output {
            path: format!("{}/{relative}", self.root),
            bytes: text.into_bytes(),
        });
    }

    fn page(&mut self, service: &str, name: &str, node: &Node) -> String {
        self.write(&format!("{service}/{name}.yaml"), node);
        let dir = self.root.rsplit('/').next().unwrap_or(&self.root);
        format!("{dir}/{service}/{name}.yaml")
    }
}

pub fn run(repo: &Repo, cfg: &Config) -> Result<Vec<Output>> {
    let Some(root) = cfg.option_str(ID, "out-dir")? else {
        return Ok(Vec::new());
    };
    let specs = Paths::new(&cfg.option_strings(ID, "specs", &["services/*/openapi.yaml"])?)?;
    let skip = cfg.option_strings(ID, "skip", &["_template"])?;
    let header = cfg
        .option_str(ID, "header")?
        .unwrap_or_else(|| DEFAULT_HEADER.to_owned());
    let mut writer = Writer {
        root: root.clone(),
        header,
        out: Vec::new(),
    };
    let mut refs = Vec::new();
    let mut groups = vec![menu_link("link_dashboard", "dashboard", "Dashboard")];
    for path in repo.files.iter().filter(|f| specs.matches(f)) {
        let Some(service) = path.split('/').rev().nth(1) else {
            continue;
        };
        if skip.iter().any(|s| s == service) {
            continue;
        }
        let text = repo.read(path).with_context(|| format!("read {path}"))?;
        let docs = yaml::load(&text).with_context(|| format!("parse {path}"))?;
        let Some(doc) = docs.first() else {
            continue;
        };
        let (page_refs, links) = gen_service(service, doc, &mut writer);
        refs.extend(page_refs);
        if !links.is_empty() {
            groups.push(Node::Struct(vec![
                ("id".to_owned(), format!("group_{service}").into()),
                ("type".to_owned(), "MenuGroup".into()),
                (
                    "properties".to_owned(),
                    map([("title", title(service).into())]),
                ),
                ("links".to_owned(), Node::List(links)),
            ]));
        }
    }
    writer.write(
        "menu.yaml",
        &Node::List(vec![map([
            ("id", "default".into()),
            ("links", Node::List(groups)),
        ])]),
    );
    let admin_dir = root.rsplit_once('/').map_or("", |(dir, _)| dir);
    let mut all = static_refs(repo, admin_dir);
    all.extend(refs);
    let manifest = all
        .into_iter()
        .map(|r| map([("_ref", r.into())]))
        .collect::<Vec<_>>();
    writer.write("pages.yaml", &Node::List(manifest));
    Ok(writer.out)
}

/// The hand-written pages in `pages/` and `custom/`, one or two levels deep.
fn static_refs(repo: &Repo, admin_dir: &str) -> Vec<String> {
    let prefix = format!("{admin_dir}/");
    let mut out = Vec::new();
    for dir in ["pages", "custom"] {
        let mut found: Vec<&str> = repo
            .files
            .iter()
            .filter_map(|f| f.strip_prefix(&prefix))
            .filter(|f| {
                f.strip_prefix(dir)
                    .and_then(|r| r.strip_prefix('/'))
                    .is_some_and(|r| r.ends_with(".yaml") && r.matches('/').count() <= 1)
            })
            .collect();
        found.sort_unstable();
        out.extend(found.into_iter().map(str::to_owned));
    }
    out
}

fn field<'a>(node: &'a MarkedYaml<'a>, key: &str) -> Option<&'a MarkedYaml<'a>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .map(|(_, v)| v)
}

fn text_of(node: &MarkedYaml<'_>, key: &str) -> String {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .and_then(|(_, v)| yaml::text(v))
        .unwrap_or_default()
}

fn json_schema<'a>(body: &'a MarkedYaml<'a>) -> Option<&'a MarkedYaml<'a>> {
    field(field(body, "content")?, "application/json").and_then(|j| field(j, "schema"))
}

fn parse_op<'a>(node: &'a MarkedYaml<'a>, method: &str, path: &str) -> Op<'a> {
    let responses = field(node, "responses");
    let response = responses.and_then(|r| {
        field(r, "200")
            .or_else(|| field(r, "201"))
            .or_else(|| numeric_key(r, 200))
            .or_else(|| numeric_key(r, 201))
    });
    let has_201 =
        responses.is_some_and(|r| field(r, "201").is_some() || numeric_key(r, 201).is_some());
    Op {
        id: text_of(node, "operationId"),
        admin: text_of(node, "x-admin"),
        tags: field(node, "tags")
            .map(|t| yaml::items(t).iter().filter_map(yaml::text).collect())
            .unwrap_or_default(),
        path_params: field(node, "parameters")
            .map(|p| {
                yaml::items(p)
                    .iter()
                    .filter(|x| text_of(x, "in") == "path")
                    .map(|x| text_of(x, "name"))
                    .collect()
            })
            .unwrap_or_default(),
        body: field(node, "requestBody").and_then(json_schema),
        response: response.and_then(json_schema),
        has_201,
        method: method.to_owned(),
        path: path.to_owned(),
    }
}

/// A response code can be an integer key in YAML.
fn numeric_key<'a>(node: &'a MarkedYaml<'a>, code: i64) -> Option<&'a MarkedYaml<'a>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::text(k).as_deref() == Some(code.to_string().as_str()))
        .map(|(_, v)| v)
}

fn gen_service<'a>(
    service: &str,
    root: &'a MarkedYaml<'a>,
    writer: &mut Writer,
) -> (Vec<String>, Vec<Node>) {
    let schemas = field(root, "components")
        .and_then(|c| field(c, "schemas"))
        .map(|s| {
            yaml::pairs(s)
                .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
                .collect()
        })
        .unwrap_or_default();
    let doc = Doc { schemas };
    let crud: Vec<String> = field(root, "tags")
        .map(|t| {
            yaml::items(t)
                .iter()
                .filter(|x| text_of(x, "x-admin") == "crud")
                .map(|x| text_of(x, "name"))
                .collect()
        })
        .unwrap_or_default();

    let mut resources: BTreeMap<String, Resource<'a>> = BTreeMap::new();
    let mut actions: Vec<Op<'a>> = Vec::new();
    let mut paths: Vec<(String, &'a MarkedYaml<'a>)> = field(root, "paths")
        .map(|p| {
            yaml::pairs(p)
                .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
                .collect()
        })
        .unwrap_or_default();
    paths.sort_by(|a, b| a.0.cmp(&b.0));
    for (path, methods) in paths {
        let mut ops: Vec<(String, &'a MarkedYaml<'a>)> = yaml::pairs(methods)
            .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
            .filter(|(m, _)| METHODS.contains(&m.as_str()))
            .collect();
        ops.sort_by(|a, b| a.0.cmp(&b.0));
        for (method, node) in ops {
            let op = parse_op(node, &method, &path);
            if op.admin == "action" {
                actions.push(op);
                continue;
            }
            if let Some(tag) = op.tags.iter().find(|t| crud.contains(t)).cloned() {
                resources
                    .entry(tag.clone())
                    .or_insert_with(|| Resource {
                        name: tag,
                        ..Resource::default()
                    })
                    .classify(op);
            }
        }
    }

    let (mut refs, mut links) = (Vec::new(), Vec::new());
    for resource in resources.values() {
        refs.extend(resource_pages(&doc, service, resource, writer));
        if resource.list.is_some() {
            links.push(menu_link(
                &format!("link_{}", resource.name),
                &resource.name,
                &title(&resource.name),
            ));
        }
    }
    actions.sort_by(|a, b| a.id.cmp(&b.id));
    for action in &actions {
        refs.push(action_page(&doc, service, action, writer));
        links.push(menu_link(
            &format!("link_{}", action.id),
            &action.id,
            &humanize(&action.id),
        ));
    }
    (refs, links)
}

fn menu_link(id: &str, page: &str, label: &str) -> Node {
    Node::Struct(vec![
        ("id".to_owned(), id.into()),
        ("type".to_owned(), "MenuLink".into()),
        ("pageId".to_owned(), page.into()),
        ("properties".to_owned(), map([("title", label.into())])),
    ])
}

fn resource_pages(doc: &Doc<'_>, service: &str, r: &Resource<'_>, w: &mut Writer) -> Vec<String> {
    let mut refs = Vec::new();
    let has_edit = r.update.is_some() || r.remove.is_some();
    if r.list.is_some() {
        refs.push(list_page(doc, service, r, has_edit, w));
    }
    if r.create.is_some() {
        refs.push(create_page(doc, service, r, w));
    }
    if has_edit {
        refs.push(edit_page(doc, service, r, w));
    }
    refs
}

/// A page, in the field order of the Lowdefy config.
fn page(
    id: &str,
    label: &str,
    events: Option<Node>,
    requests: Vec<Node>,
    blocks: Vec<Node>,
) -> Node {
    let mut pairs = vec![
        ("id".to_owned(), id.into()),
        ("type".to_owned(), PAGE.into()),
        (
            "properties".to_owned(),
            Node::Struct(vec![("title".to_owned(), label.into())]),
        ),
    ];
    if let Some(events) = events {
        pairs.push(("events".to_owned(), events));
    }
    if !requests.is_empty() {
        pairs.push(("requests".to_owned(), Node::List(requests)));
    }
    pairs.push(("blocks".to_owned(), Node::List(blocks)));
    Node::Struct(pairs)
}

fn request(id: &str, connection: &str, payload: Option<Node>, properties: Node) -> Node {
    let mut pairs = vec![
        ("id".to_owned(), id.into()),
        ("type".to_owned(), AXIOS.into()),
        ("connectionId".to_owned(), connection.into()),
    ];
    if let Some(payload) = payload.filter(|p| !matches!(p, Node::Map(m) if m.is_empty())) {
        pairs.push(("payload".to_owned(), payload));
    }
    pairs.push(("properties".to_owned(), properties));
    Node::Struct(pairs)
}

#[derive(Default)]
struct BlockParts {
    properties: Option<Node>,
    style: Option<Node>,
    events: Option<Node>,
    blocks: Vec<Node>,
}

fn block(id: &str, kind: &str, parts: BlockParts) -> Node {
    let mut pairs = vec![
        ("id".to_owned(), id.into()),
        ("type".to_owned(), kind.into()),
    ];
    if let Some(p) = parts.properties {
        pairs.push(("properties".to_owned(), p));
    }
    if let Some(s) = parts.style {
        pairs.push(("style".to_owned(), s));
    }
    if let Some(e) = parts.events {
        pairs.push(("events".to_owned(), e));
    }
    if !parts.blocks.is_empty() {
        pairs.push(("blocks".to_owned(), Node::List(parts.blocks)));
    }
    Node::Struct(pairs)
}

fn heading(text: &str) -> Node {
    block(
        "header",
        "Title",
        BlockParts {
            properties: Some(map([("content", text.into()), ("level", Node::Int(3))])),
            ..BlockParts::default()
        },
    )
}

fn card(id: &str, label: &str, blocks: Vec<Node>) -> Node {
    block(
        id,
        "Card",
        BlockParts {
            properties: Some(map([("title", label.into())])),
            blocks,
            ..BlockParts::default()
        },
    )
}

fn spacing() -> Node {
    map([("marginTop", Node::Int(16)), ("marginRight", Node::Int(8))])
}

fn link_button(id: &str, label: &str, page_id: &str, kind: &str) -> Node {
    let mut props = vec![("title".to_owned(), Node::from(label))];
    if !kind.is_empty() {
        props.push(("type".to_owned(), kind.into()));
    }
    let on_click = Node::List(vec![map([
        ("id", format!("{id}Link").into()),
        ("type", "Link".into()),
        ("params", map([("pageId", page_id.into())])),
    ])]);
    block(
        id,
        "Button",
        BlockParts {
            properties: Some(Node::Map(props)),
            style: Some(spacing()),
            events: Some(map([("onClick", on_click)])),
            ..BlockParts::default()
        },
    )
}

fn request_button(
    id: &str,
    label: &str,
    req: &str,
    kind: &str,
    danger: bool,
    follow: Vec<Vec<(String, Node)>>,
) -> Node {
    let mut props = vec![("title".to_owned(), Node::from(label))];
    if !kind.is_empty() {
        props.push(("type".to_owned(), kind.into()));
    }
    if danger {
        props.push(("danger".to_owned(), Node::Bool(true)));
    }
    let mut steps = vec![map([
        ("id", format!("{id}Req").into()),
        ("type", "Request".into()),
        ("params", req.into()),
    ])];
    for (i, mut step) in follow.into_iter().enumerate() {
        step.push(("id".to_owned(), format!("{id}{i}").into()));
        steps.push(Node::Map(step));
    }
    block(
        id,
        "Button",
        BlockParts {
            properties: Some(Node::Map(props)),
            style: Some(spacing()),
            events: Some(map([("onClick", Node::List(steps))])),
            ..BlockParts::default()
        },
    )
}

fn message(text: &str) -> Vec<(String, Node)> {
    vec![
        ("type".to_owned(), "DisplayMessage".into()),
        (
            "params".to_owned(),
            map([("content", text.into()), ("status", "success".into())]),
        ),
    ]
}

fn link_to(page_id: &str) -> Vec<(String, Node)> {
    vec![
        ("type".to_owned(), "Link".into()),
        ("params".to_owned(), map([("pageId", page_id.into())])),
    ]
}

fn input(state: &str, label: &str, kind: &str) -> Node {
    let widget = match kind {
        "integer" | "number" => "NumberInput",
        "boolean" => "Switch",
        _ if label == "password" => "PasswordInput",
        _ => "TextInput",
    };
    block(
        state,
        widget,
        BlockParts {
            properties: Some(map([(
                "label",
                map([("title", header_name(label).into())]),
            )])),
            ..BlockParts::default()
        },
    )
}

/// A money field is an amount and a currency. The amount is text, because a number input returns a double.
fn inputs_for(p: &Prop) -> Vec<Node> {
    if p.is_money() {
        return vec![
            input(&format!("{}.amount", p.name), &p.name, "string"),
            input(&format!("{}.currency", p.name), "currency", "string"),
        ];
    }
    vec![input(&p.name, &p.name, &p.kind)]
}

fn state(key: &str) -> Node {
    map([("_state", key.into())])
}

fn payload_ref(key: &str) -> Node {
    map([("_payload", key.into())])
}

fn list_page(
    doc: &Doc<'_>,
    service: &str,
    r: &Resource<'_>,
    has_edit: bool,
    w: &mut Writer,
) -> String {
    let Some(list) = &r.list else {
        return String::new();
    };
    let label = title(&r.name);
    let req = request(
        "list",
        service,
        None,
        map([("url", list.path.as_str().into()), ("method", "get".into())]),
    );
    let events = map([(
        "onMount",
        Node::List(vec![map([
            ("id", "loadList".into()),
            ("type", "Request".into()),
            ("params", "list".into()),
        ])]),
    )]);
    let mut blocks = vec![heading(&label)];
    if r.create.is_some() {
        blocks.push(link_button(
            "add",
            &format!("Add {}", singular(&r.name)),
            &format!("{}_new", r.name),
            "primary",
        ));
    }
    let table_props = map([
        ("rowData", map([("_request", "list.data".into())])),
        ("columnDefs", column_defs(doc, list.response)),
        ("pagination", Node::Bool(true)),
        ("paginationPageSize", Node::Int(LIST_PAGE_SIZE)),
    ]);
    let table_events = has_edit.then(|| {
        map([(
            "onRowClick",
            Node::List(vec![map([
                ("id", "openRow".into()),
                ("type", "Link".into()),
                (
                    "params",
                    map([
                        ("pageId", format!("{}_edit", r.name).into()),
                        (
                            "urlQuery",
                            map([("id", map([("_event", "row.id".into())]))]),
                        ),
                    ]),
                ),
            ])]),
        )])
    });
    if has_edit {
        blocks.push(block(
            "hint",
            "Paragraph",
            BlockParts {
                properties: Some(map([("content", "Click a row to edit.".into())])),
                ..BlockParts::default()
            },
        ));
    }
    let table = block(
        "table",
        "AgGridAlpine",
        BlockParts {
            properties: Some(table_props),
            events: table_events,
            ..BlockParts::default()
        },
    );
    blocks.push(card(&format!("{}_card", r.name), &label, vec![table]));
    w.page(
        service,
        &r.name,
        &page(&r.name, &label, Some(events), vec![req], blocks),
    )
}

fn create_page(doc: &Doc<'_>, service: &str, r: &Resource<'_>, w: &mut Writer) -> String {
    let Some(create) = &r.create else {
        return String::new();
    };
    let one = singular(&r.name);
    let id = format!("{}_new", r.name);
    let fields = props(doc, create.body);
    let mut form = Vec::new();
    let (mut payload, mut data) = (Vec::new(), Vec::new());
    for f in &fields {
        form.extend(inputs_for(f));
        payload.push((f.name.clone(), state(&f.name)));
        data.push((f.name.clone(), payload_ref(&f.name)));
    }
    let req = request(
        "create",
        service,
        Some(Node::Map(payload)),
        map([
            ("url", path_to_url(&create.path)),
            ("method", "post".into()),
            ("data", Node::Map(data)),
        ]),
    );
    form.push(request_button(
        "submit",
        "Create",
        "create",
        "primary",
        false,
        vec![message(&format!("Created {one}")), link_to(&r.name)],
    ));
    form.push(link_button("back", "Back to list", &r.name, ""));
    let blocks = vec![
        heading(&format!("Add {one}")),
        card(&format!("{}_form", r.name), &format!("New {one}"), form),
    ];
    w.page(
        service,
        &id,
        &page(&id, &format!("Add {one}"), None, vec![req], blocks),
    )
}

#[expect(
    clippy::too_many_lines,
    reason = "one page, in the order that it renders"
)]
fn edit_page(doc: &Doc<'_>, service: &str, r: &Resource<'_>, w: &mut Writer) -> String {
    let one = singular(&r.name);
    let id = format!("{}_edit", r.name);
    let from_query = || map([("_url_query", "id".into())]);
    let fields = r
        .update
        .as_ref()
        .map_or_else(Vec::new, |u| props(doc, u.body));
    let mut requests = Vec::new();
    let mut events = None;
    if let Some(get) = &r.get {
        requests.push(request(
            "get",
            service,
            Some(map([("id", from_query())])),
            map([("url", path_to_url(&get.path)), ("method", "get".into())]),
        ));
        let fill = fields
            .iter()
            .map(|f| {
                let value = map([("_request", format!("get.data.{}", f.name).into())]);
                let value = if f.kind == "string" && f.reference.is_empty() {
                    map([("_if_none", Node::List(vec![value, "".into()]))])
                } else {
                    value
                };
                (f.name.clone(), value)
            })
            .collect();
        events = Some(map([(
            "onMount",
            Node::List(vec![
                map([
                    ("id", "load".into()),
                    ("type", "Request".into()),
                    ("params", "get".into()),
                ]),
                map([
                    ("id", "fill".into()),
                    ("type", "SetState".into()),
                    ("params", Node::Map(fill)),
                ]),
            ]),
        )]));
    }
    let mut form = vec![block(
        "id_display",
        "Paragraph",
        BlockParts {
            properties: Some(map([(
                "content",
                map([(
                    "_string.concat",
                    Node::List(vec!["Editing id: ".into(), from_query()]),
                )]),
            )])),
            ..BlockParts::default()
        },
    )];
    for f in &fields {
        form.extend(inputs_for(f));
    }
    if let Some(update) = &r.update {
        let mut payload = vec![("id".to_owned(), from_query())];
        let mut data = Vec::new();
        for f in &fields {
            payload.push((f.name.clone(), state(&f.name)));
            data.push((f.name.clone(), payload_ref(&f.name)));
        }
        requests.push(request(
            "update",
            service,
            Some(Node::Map(payload)),
            map([
                ("url", path_to_url(&update.path)),
                ("method", "put".into()),
                ("data", Node::Map(data)),
            ]),
        ));
        form.push(request_button(
            "save",
            "Save",
            "update",
            "primary",
            false,
            vec![message("Saved changes")],
        ));
    }
    if let Some(remove) = &r.remove {
        requests.push(request(
            "remove",
            service,
            Some(map([("id", from_query())])),
            map([
                ("url", path_to_url(&remove.path)),
                ("method", "delete".into()),
            ]),
        ));
        form.push(request_button(
            "delete",
            "Delete",
            "remove",
            "",
            true,
            vec![link_to(&r.name)],
        ));
    }
    form.push(link_button("back", "Back to list", &r.name, ""));
    let blocks = vec![
        heading(&format!("Edit {one}")),
        card(&format!("{}_form", r.name), &format!("Edit {one}"), form),
    ];
    w.page(
        service,
        &id,
        &page(&id, &format!("Edit {one}"), events, requests, blocks),
    )
}

fn action_page(doc: &Doc<'_>, service: &str, o: &Op<'_>, w: &mut Writer) -> String {
    let label = humanize(&o.id);
    let mut form = Vec::new();
    let (mut payload, mut data) = (Vec::new(), Vec::new());
    for name in &o.path_params {
        form.push(input(name, name, "string"));
        payload.push((name.clone(), state(name)));
    }
    for p in props(doc, o.body) {
        form.push(input(&p.name, &p.name, &p.kind));
        payload.push((p.name.clone(), state(&p.name)));
        data.push((p.name.clone(), payload_ref(&p.name)));
    }
    let mut properties = vec![
        ("url".to_owned(), path_to_url(&o.path)),
        ("method".to_owned(), o.method.as_str().into()),
    ];
    if !data.is_empty() {
        properties.push(("data".to_owned(), Node::Map(data)));
    }
    let req = request(
        "run",
        service,
        Some(Node::Map(payload)),
        Node::Map(properties),
    );
    form.push(request_button(
        "submit",
        &label,
        "run",
        "primary",
        false,
        vec![message(&format!("{label} succeeded"))],
    ));
    let blocks = vec![
        heading(&label),
        card(&format!("{}_form", o.id), &label, form),
    ];
    w.page(
        service,
        &o.id,
        &page(&o.id, &label, None, vec![req], blocks),
    )
}

fn column_defs(doc: &Doc<'_>, schema: Option<&MarkedYaml<'_>>) -> Node {
    let mut defs = Vec::new();
    for c in props(doc, schema) {
        if c.is_money() {
            defs.push(map([
                ("field", format!("{}.amount", c.name).into()),
                ("headerName", header_name(&c.name).into()),
            ]));
            defs.push(map([
                ("field", format!("{}.currency", c.name).into()),
                ("headerName", "Currency".into()),
            ]));
        } else {
            defs.push(map([
                ("field", c.name.as_str().into()),
                ("headerName", header_name(&c.name).into()),
            ]));
        }
    }
    Node::List(defs)
}

/// The ordered properties of a schema. It follows a `$ref` and unwraps an array to its items.
fn props(doc: &Doc<'_>, schema: Option<&MarkedYaml<'_>>) -> Vec<Prop> {
    let Some(schema) = schema else {
        return Vec::new();
    };
    let lookup = |key: &str| {
        yaml::pairs(schema)
            .find(|(k, _)| yaml::string(k) == Some(key))
            .map(|(_, v)| v)
    };
    let text = |key: &str| lookup(key).and_then(yaml::text).unwrap_or_default();
    let reference = text("$ref");
    if !reference.is_empty() {
        let name = reference.rsplit('/').next().unwrap_or_default();
        return doc
            .schemas
            .get(name)
            .map_or_else(Vec::new, |target| props(doc, Some(target)));
    }
    if text("type") == "array" {
        return props(doc, lookup("items"));
    }
    lookup("properties").map_or_else(Vec::new, |p| {
        yaml::pairs(p)
            .map(|(k, v)| Prop {
                name: yaml::text(k).unwrap_or_default(),
                kind: text_of_any(v, "type"),
                reference: text_of_any(v, "$ref"),
            })
            .collect()
    })
}

fn text_of_any(node: &MarkedYaml<'_>, key: &str) -> String {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .and_then(|(_, v)| yaml::text(v))
        .unwrap_or_default()
}

/// A plain url, or a `_string.concat` that inserts the path params from the payload.
fn path_to_url(path: &str) -> Node {
    if !path.contains('{') {
        return path.into();
    }
    let mut parts = Vec::new();
    let mut rest = path;
    while let Some(open) = rest.find('{') {
        if open > 0 {
            parts.push(Node::from(&rest[..open]));
        }
        let Some(close) = rest[open..].find('}') else {
            break;
        };
        parts.push(payload_ref(&rest[open + 1..open + close]));
        rest = &rest[open + close + 1..];
    }
    if !rest.is_empty() {
        parts.push(rest.into());
    }
    map([("_string.concat", Node::List(parts))])
}

fn title(text: &str) -> String {
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |c| {
        c.to_ascii_uppercase().to_string() + chars.as_str()
    })
}

fn singular(text: &str) -> String {
    if let Some(stem) = text.strip_suffix("ies").filter(|_| text.len() > 3) {
        return format!("{stem}y");
    }
    if let Some(stem) = text.strip_suffix('s').filter(|_| text.len() > 1) {
        return stem.to_owned();
    }
    text.to_owned()
}

fn header_name(text: &str) -> String {
    title(&text.replace('_', " "))
}

fn humanize(text: &str) -> String {
    let mut out = String::new();
    for (i, c) in text.chars().enumerate() {
        if i > 0 && c.is_ascii_uppercase() {
            out.push(' ');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    title(&out)
}

