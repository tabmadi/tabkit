//! `gen/admin`: the page manifest of the admin console from the OpenAPI specs. A tag with `x-admin: crud` becomes
//! list, add, and edit pages, and an operation with `x-admin: action` becomes one form. The console renders the manifest.

use std::collections::BTreeMap;

use anyhow::{Context, Result};
use saphyr::MarkedYaml;
use serde::Serialize;

use super::Output;
use tabkit_core::config::{Config, Paths};
use tabkit_core::repo::Repo;
use tabkit_core::yaml;

const ID: &str = "gen/admin";
const DEFAULT_COMMENT: &str = "Generated by tabkit. Do not edit.";
const METHODS: [&str; 8] = [
    "get", "put", "post", "delete", "patch", "options", "head", "trace",
];
const LIST_PAGE_SIZE: usize = 20;

/// The directory that this generator owns, so a file of an older format goes away.
pub fn owned(cfg: &Config) -> Result<Option<String>> {
    cfg.option_str(ID, "out-dir")
}

#[derive(Clone, Default)]
struct Prop {
    name: String,
    kind: String,
    reference: String,
}

impl Prop {
    fn is_money(&self) -> bool {
        self.reference.rsplit('/').next() == Some("Money") && !self.reference.is_empty()
    }
}

#[derive(Clone)]
struct Op<'a> {
    id: String,
    admin: String,
    tags: Vec<String>,
    path_params: Vec<String>,
    body: Option<&'a MarkedYaml<'a>>,
    response: Option<&'a MarkedYaml<'a>>,
    has_201: bool,
    method: String,
    path: String,
}

impl Op<'_> {
    fn segments(&self) -> usize {
        self.path.split('/').filter(|s| !s.is_empty()).count()
    }
}

#[derive(Default)]
struct Resource<'a> {
    name: String,
    list: Option<Op<'a>>,
    get: Option<Op<'a>>,
    create: Option<Op<'a>>,
    update: Option<Op<'a>>,
    remove: Option<Op<'a>>,
}

impl<'a> Resource<'a> {
    /// An async create, a POST that returns 202, starts a workflow and stays unassigned.
    fn classify(&mut self, op: Op<'a>) {
        let two = op.segments() == 2;
        match op.method.as_str() {
            "get" if op.path_params.is_empty() => self.list = Some(op),
            "get" if two => self.get = Some(op),
            "post" if op.path_params.is_empty() && op.has_201 => self.create = Some(op),
            "put" if two => self.update = Some(op),
            "delete" if two => self.remove = Some(op),
            _ => {}
        }
    }
}

struct Doc<'a> {
    schemas: BTreeMap<String, &'a MarkedYaml<'a>>,
}

/// The manifest that the console reads. Every page has an id that is also its URL path.
#[derive(Serialize)]
struct Manifest {
    #[serde(rename = "$comment")]
    comment: String,
    #[serde(rename = "pageSize")]
    page_size: usize,
    groups: Vec<Group>,
    pages: Vec<Page>,
}

#[derive(Serialize)]
struct Group {
    service: String,
    title: String,
    links: Vec<Link>,
}

#[derive(Serialize)]
struct Link {
    page: String,
    title: String,
}

#[derive(Serialize)]
struct Column {
    field: String,
    header: String,
}

/// One input. A dotted name, such as `price.amount`, is a nested property of the request body.
#[derive(Serialize, Debug, PartialEq, Eq)]
struct Field {
    name: String,
    label: String,
    kind: String,
}

#[derive(Serialize)]
struct Call {
    method: String,
    path: String,
}

#[derive(Serialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
enum Page {
    List {
        id: String,
        service: String,
        title: String,
        list: Call,
        columns: Vec<Column>,
        #[serde(skip_serializing_if = "Option::is_none")]
        add: Option<Link>,
        #[serde(skip_serializing_if = "Option::is_none")]
        edit: Option<String>,
    },
    Create {
        id: String,
        service: String,
        title: String,
        create: Call,
        fields: Vec<Field>,
        back: String,
        done: String,
    },
    Edit {
        id: String,
        service: String,
        title: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        get: Option<Call>,
        #[serde(skip_serializing_if = "Option::is_none")]
        update: Option<Call>,
        #[serde(skip_serializing_if = "Option::is_none")]
        remove: Option<Call>,
        fields: Vec<Field>,
        back: String,
    },
    Action {
        id: String,
        service: String,
        title: String,
        run: Call,
        params: Vec<Field>,
        fields: Vec<Field>,
    },
}

pub fn run(repo: &Repo, cfg: &Config) -> Result<Vec<Output>> {
    let Some(root) = cfg.option_str(ID, "out-dir")? else {
        return Ok(Vec::new());
    };
    let specs = Paths::new(&cfg.option_strings(ID, "specs", &["services/*/openapi.yaml"])?)?;
    let skip = cfg.option_strings(ID, "skip", &["_template"])?;
    let comment = cfg.option_str(ID, "header")?.map_or_else(
        || DEFAULT_COMMENT.to_owned(),
        |h| h.trim().trim_start_matches('#').trim().to_owned(),
    );
    let mut manifest = Manifest {
        comment,
        page_size: LIST_PAGE_SIZE,
        groups: Vec::new(),
        pages: Vec::new(),
    };
    for path in repo.files.iter().filter(|f| specs.matches(f)) {
        let Some(service) = path.split('/').rev().nth(1) else {
            continue;
        };
        if skip.iter().any(|s| s == service) {
            continue;
        }
        let text = repo.read(path).with_context(|| format!("read {path}"))?;
        let docs = yaml::load(&text).with_context(|| format!("parse {path}"))?;
        let Some(doc) = docs.first() else {
            continue;
        };
        let links = gen_service(service, doc, &mut manifest.pages);
        if !links.is_empty() {
            manifest.groups.push(Group {
                service: service.to_owned(),
                title: title(service),
                links,
            });
        }
    }
    let mut bytes = serde_json::to_vec_pretty(&manifest)?;
    bytes.push(b'\n');
    Ok(vec![Output {
        path: format!("{root}/manifest.json"),
        bytes,
    }])
}

fn field<'a>(node: &'a MarkedYaml<'a>, key: &str) -> Option<&'a MarkedYaml<'a>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .map(|(_, v)| v)
}

fn text_of(node: &MarkedYaml<'_>, key: &str) -> String {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .and_then(|(_, v)| yaml::text(v))
        .unwrap_or_default()
}

fn json_schema<'a>(body: &'a MarkedYaml<'a>) -> Option<&'a MarkedYaml<'a>> {
    field(field(body, "content")?, "application/json").and_then(|j| field(j, "schema"))
}

fn parse_op<'a>(node: &'a MarkedYaml<'a>, method: &str, path: &str) -> Op<'a> {
    let responses = field(node, "responses");
    let response = responses.and_then(|r| {
        field(r, "200")
            .or_else(|| field(r, "201"))
            .or_else(|| numeric_key(r, 200))
            .or_else(|| numeric_key(r, 201))
    });
    let has_201 =
        responses.is_some_and(|r| field(r, "201").is_some() || numeric_key(r, 201).is_some());
    Op {
        id: text_of(node, "operationId"),
        admin: text_of(node, "x-admin"),
        tags: field(node, "tags")
            .map(|t| yaml::items(t).iter().filter_map(yaml::text).collect())
            .unwrap_or_default(),
        path_params: field(node, "parameters")
            .map(|p| {
                yaml::items(p)
                    .iter()
                    .filter(|x| text_of(x, "in") == "path")
                    .map(|x| text_of(x, "name"))
                    .collect()
            })
            .unwrap_or_default(),
        body: field(node, "requestBody").and_then(json_schema),
        response: response.and_then(json_schema),
        has_201,
        method: method.to_owned(),
        path: path.to_owned(),
    }
}

/// A response code can be an integer key in YAML.
fn numeric_key<'a>(node: &'a MarkedYaml<'a>, code: i64) -> Option<&'a MarkedYaml<'a>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::text(k).as_deref() == Some(code.to_string().as_str()))
        .map(|(_, v)| v)
}

fn gen_service<'a>(service: &str, root: &'a MarkedYaml<'a>, pages: &mut Vec<Page>) -> Vec<Link> {
    let schemas = field(root, "components")
        .and_then(|c| field(c, "schemas"))
        .map(|s| {
            yaml::pairs(s)
                .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
                .collect()
        })
        .unwrap_or_default();
    let doc = Doc { schemas };
    let crud: Vec<String> = field(root, "tags")
        .map(|t| {
            yaml::items(t)
                .iter()
                .filter(|x| text_of(x, "x-admin") == "crud")
                .map(|x| text_of(x, "name"))
                .collect()
        })
        .unwrap_or_default();

    let mut resources: BTreeMap<String, Resource<'a>> = BTreeMap::new();
    let mut actions: Vec<Op<'a>> = Vec::new();
    let mut paths: Vec<(String, &'a MarkedYaml<'a>)> = field(root, "paths")
        .map(|p| {
            yaml::pairs(p)
                .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
                .collect()
        })
        .unwrap_or_default();
    paths.sort_by(|a, b| a.0.cmp(&b.0));
    for (path, methods) in paths {
        let mut ops: Vec<(String, &'a MarkedYaml<'a>)> = yaml::pairs(methods)
            .filter_map(|(k, v)| Some((yaml::text(k)?, v)))
            .filter(|(m, _)| METHODS.contains(&m.as_str()))
            .collect();
        ops.sort_by(|a, b| a.0.cmp(&b.0));
        for (method, node) in ops {
            let op = parse_op(node, &method, &path);
            if op.admin == "action" {
                actions.push(op);
                continue;
            }
            if let Some(tag) = op.tags.iter().find(|t| crud.contains(t)).cloned() {
                resources
                    .entry(tag.clone())
                    .or_insert_with(|| Resource {
                        name: tag,
                        ..Resource::default()
                    })
                    .classify(op);
            }
        }
    }

    let mut links = Vec::new();
    for r in resources.values() {
        resource_pages(&doc, service, r, pages);
        if r.list.is_some() {
            links.push(Link {
                page: r.name.clone(),
                title: title(&r.name),
            });
        }
    }
    actions.sort_by(|a, b| a.id.cmp(&b.id));
    for o in &actions {
        let label = humanize(&o.id);
        pages.push(Page::Action {
            id: o.id.clone(),
            service: service.to_owned(),
            title: label.clone(),
            run: call(o),
            params: o
                .path_params
                .iter()
                .map(|n| Field {
                    name: n.clone(),
                    label: header_name(n),
                    kind: "string".to_owned(),
                })
                .collect(),
            fields: fields(&props(&doc, o.body)),
        });
        links.push(Link {
            page: o.id.clone(),
            title: label,
        });
    }
    links
}

fn call(op: &Op<'_>) -> Call {
    Call {
        method: op.method.clone(),
        path: op.path.clone(),
    }
}

fn resource_pages(doc: &Doc<'_>, service: &str, r: &Resource<'_>, pages: &mut Vec<Page>) {
    let one = singular(&r.name);
    let has_edit = r.update.is_some() || r.remove.is_some();
    if let Some(list) = &r.list {
        pages.push(Page::List {
            id: r.name.clone(),
            service: service.to_owned(),
            title: title(&r.name),
            list: call(list),
            columns: columns(&props(doc, list.response)),
            add: r.create.as_ref().map(|_| Link {
                page: format!("{}_new", r.name),
                title: format!("Add {one}"),
            }),
            edit: has_edit.then(|| format!("{}_edit", r.name)),
        });
    }
    if let Some(create) = &r.create {
        pages.push(Page::Create {
            id: format!("{}_new", r.name),
            service: service.to_owned(),
            title: format!("Add {one}"),
            create: call(create),
            fields: fields(&props(doc, create.body)),
            back: r.name.clone(),
            done: format!("Created {one}"),
        });
    }
    if has_edit {
        let body = r
            .update
            .as_ref()
            .map_or_else(Vec::new, |u| props(doc, u.body));
        pages.push(Page::Edit {
            id: format!("{}_edit", r.name),
            service: service.to_owned(),
            title: format!("Edit {one}"),
            get: r.get.as_ref().map(call),
            update: r.update.as_ref().map(call),
            remove: r.remove.as_ref().map(call),
            fields: fields(&body),
            back: r.name.clone(),
        });
    }
}

/// A money field is an amount and a currency. The amount is text, because a number input returns a double.
fn fields(props: &[Prop]) -> Vec<Field> {
    let mut out = Vec::new();
    for p in props {
        if p.is_money() {
            out.push(Field {
                name: format!("{}.amount", p.name),
                label: header_name(&p.name),
                kind: "string".to_owned(),
            });
            out.push(Field {
                name: format!("{}.currency", p.name),
                label: "Currency".to_owned(),
                kind: "string".to_owned(),
            });
        } else {
            let kind = match p.kind.as_str() {
                "integer" | "number" | "boolean" => p.kind.clone(),
                _ if p.name == "password" => "password".to_owned(),
                _ => "string".to_owned(),
            };
            out.push(Field {
                name: p.name.clone(),
                label: header_name(&p.name),
                kind,
            });
        }
    }
    out
}

fn columns(props: &[Prop]) -> Vec<Column> {
    fields(props)
        .into_iter()
        .map(|f| Column {
            field: f.name,
            header: f.label,
        })
        .collect()
}

/// The ordered properties of a schema. It follows a `$ref` and unwraps an array to its items.
fn props(doc: &Doc<'_>, schema: Option<&MarkedYaml<'_>>) -> Vec<Prop> {
    let Some(schema) = schema else {
        return Vec::new();
    };
    let lookup = |key: &str| {
        yaml::pairs(schema)
            .find(|(k, _)| yaml::string(k) == Some(key))
            .map(|(_, v)| v)
    };
    let text = |key: &str| lookup(key).and_then(yaml::text).unwrap_or_default();
    let reference = text("$ref");
    if !reference.is_empty() {
        let name = reference.rsplit('/').next().unwrap_or_default();
        return doc
            .schemas
            .get(name)
            .map_or_else(Vec::new, |target| props(doc, Some(target)));
    }
    if text("type") == "array" {
        return props(doc, lookup("items"));
    }
    lookup("properties").map_or_else(Vec::new, |p| {
        yaml::pairs(p)
            .map(|(k, v)| Prop {
                name: yaml::text(k).unwrap_or_default(),
                kind: text_of_any(v, "type"),
                reference: text_of_any(v, "$ref"),
            })
            .collect()
    })
}

fn text_of_any(node: &MarkedYaml<'_>, key: &str) -> String {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .and_then(|(_, v)| yaml::text(v))
        .unwrap_or_default()
}

fn title(text: &str) -> String {
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |c| {
        c.to_ascii_uppercase().to_string() + chars.as_str()
    })
}

fn singular(text: &str) -> String {
    if let Some(stem) = text.strip_suffix("ies").filter(|_| text.len() > 3) {
        return format!("{stem}y");
    }
    if let Some(stem) = text.strip_suffix('s').filter(|_| text.len() > 1) {
        return stem.to_owned();
    }
    text.to_owned()
}

fn header_name(text: &str) -> String {
    title(&text.replace('_', " "))
}

fn humanize(text: &str) -> String {
    let mut out = String::new();
    for (i, c) in text.chars().enumerate() {
        if i > 0 && c.is_ascii_uppercase() {
            out.push(' ');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    title(&out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn labels() {
        assert_eq!(title("products"), "Products");
        assert_eq!(header_name("price_cents"), "Price cents");
        assert_eq!(humanize("refundCharge"), "Refund charge");
        assert_eq!(singular("products"), "product");
        assert_eq!(singular("orgs"), "org");
        assert_eq!(singular("identities"), "identity");
    }

    fn op(method: &str, path: &str, has_201: bool, params: &[&str]) -> Op<'static> {
        Op {
            id: String::new(),
            admin: String::new(),
            tags: Vec::new(),
            path_params: params.iter().map(|p| (*p).to_owned()).collect(),
            body: None,
            response: None,
            has_201,
            method: method.to_owned(),
            path: path.to_owned(),
        }
    }

    #[test]
    fn a_sync_create_is_a_form_and_an_async_create_is_not() {
        let mut r = Resource::default();
        r.classify(op("get", "/products", false, &[]));
        r.classify(op("get", "/products/{id}", false, &["id"]));
        r.classify(op("post", "/products", true, &[]));
        r.classify(op("put", "/products/{id}", false, &["id"]));
        r.classify(op("delete", "/products/{id}", false, &["id"]));
        assert!(r.list.is_some() && r.get.is_some() && r.create.is_some());
        assert!(r.update.is_some() && r.remove.is_some());

        let mut asynchronous = Resource::default();
        asynchronous.classify(op("get", "/orders", false, &[]));
        asynchronous.classify(op("post", "/orders", false, &[]));
        assert!(asynchronous.list.is_some());
        assert!(asynchronous.create.is_none());
    }

    #[test]
    fn a_money_field_is_two_text_inputs() {
        let price = Prop {
            name: "price".to_owned(),
            kind: String::new(),
            reference: "#/components/schemas/Money".to_owned(),
        };
        let got = fields(&[price]);
        assert_eq!(got.len(), 2);
        assert_eq!(got[0].name, "price.amount");
        assert_eq!(got[0].label, "Price");
        assert_eq!(got[1].label, "Currency");
    }
}
