//! `gen/zod`: a zod schema for each JSON request body of every OpenAPI spec.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use anyhow::{Context, Result, anyhow, bail};
use saphyr::MarkedYaml;

use super::Output;
use tabkit_core::config::{Config, Paths};
use tabkit_core::repo::Repo;
use tabkit_core::yaml;

const ID: &str = "gen/zod";
const DEFAULT_HEADER: &str = "// Generated by tabkit from {service}/openapi.yaml. Do not edit.\nimport { z } from \"zod\";\n";

#[derive(Default)]
struct Schema {
    reference: String,
    kind: String,
    required: Vec<String>,
    properties: BTreeMap<String, Schema>,
    items: Option<Box<Schema>>,
    values: Vec<String>,
    format: String,
    pattern: String,
    min_length: Option<i64>,
    max_length: Option<i64>,
    minimum: Option<f64>,
    maximum: Option<f64>,
}

pub fn run(repo: &Repo, cfg: &Config) -> Result<Vec<Output>> {
    let Some(out_dir) = cfg.option_str(ID, "out-dir")? else {
        return Ok(Vec::new());
    };
    let specs = Paths::new(&cfg.option_strings(ID, "specs", &["services/*/openapi.yaml"])?)?;
    let skip = cfg.option_strings(ID, "skip", &["_template"])?;
    let header = cfg
        .option_str(ID, "header")?
        .unwrap_or_else(|| DEFAULT_HEADER.to_owned());
    let mut out = Vec::new();
    for path in repo.files.iter().filter(|f| specs.matches(f)) {
        let Some(service) = path.split('/').rev().nth(1) else {
            continue;
        };
        if skip.iter().any(|s| s == service) {
            continue;
        }
        let text = repo.read(path).with_context(|| format!("read {path}"))?;
        let rendered = render(service, &text, &header).with_context(|| path.clone())?;
        if let Some(module) = rendered {
            out.push(Output {
                path: format!("{out_dir}/{service}.ts"),
                bytes: module.into_bytes(),
            });
        }
    }
    Ok(out)
}

fn field<'a, 'b>(node: &'a MarkedYaml<'b>, key: &str) -> Option<&'a MarkedYaml<'b>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(key))
        .map(|(_, v)| v)
}

fn parse_schema(node: &MarkedYaml<'_>) -> Schema {
    let text = |key: &str| field(node, key).and_then(yaml::text).unwrap_or_default();
    let list = |key: &str| -> Vec<String> {
        field(node, key)
            .map(|v| yaml::items(v).iter().filter_map(yaml::text).collect())
            .unwrap_or_default()
    };
    let int = |key: &str| field(node, key).and_then(yaml::text)?.parse().ok();
    let float = |key: &str| field(node, key).and_then(yaml::text)?.parse().ok();
    Schema {
        reference: text("$ref"),
        kind: text("type"),
        required: list("required"),
        properties: field(node, "properties").map_or_else(BTreeMap::new, |p| {
            yaml::pairs(p)
                .filter_map(|(k, v)| Some((yaml::text(k)?, parse_schema(v))))
                .collect()
        }),
        items: field(node, "items").map(|v| Box::new(parse_schema(v))),
        values: list("enum"),
        format: text("format"),
        pattern: text("pattern"),
        min_length: int("minLength"),
        max_length: int("maxLength"),
        minimum: float("minimum"),
        maximum: float("maximum"),
    }
}

fn render(service: &str, text: &str, header: &str) -> Result<Option<String>> {
    let docs = yaml::load(text).map_err(|e| anyhow!("parse spec: {e}"))?;
    let Some(doc) = docs.first() else {
        return Ok(None);
    };
    let components: BTreeMap<String, Schema> = field(doc, "components")
        .and_then(|c| field(c, "schemas"))
        .map_or_else(BTreeMap::new, |s| {
            yaml::pairs(s)
                .filter_map(|(k, v)| Some((yaml::text(k)?, parse_schema(v))))
                .collect()
        });
    let mut bodies: Vec<(String, Schema)> = Vec::new();
    if let Some(paths) = field(doc, "paths") {
        for (_, operations) in yaml::pairs(paths) {
            for (_, operation) in yaml::pairs(operations) {
                let schema = field(operation, "requestBody")
                    .and_then(|b| field(b, "content"))
                    .and_then(|c| field(c, "application/json"))
                    .and_then(|j| field(j, "schema"));
                if let Some(schema) = schema {
                    let id = field(operation, "operationId")
                        .and_then(yaml::text)
                        .unwrap_or_default();
                    bodies.push((id, parse_schema(schema)));
                }
            }
        }
    }
    if bodies.is_empty() {
        return Ok(None);
    }
    bodies.sort_by(|a, b| a.0.cmp(&b.0));

    let mut b = header.replace("{service}", service);
    let mut needed = BTreeSet::new();
    for (_, schema) in &bodies {
        collect(schema, &components, &mut needed);
    }
    for name in dependency_order(&needed, &components) {
        let expr = zod_of(&components[&name], &components, 0)
            .with_context(|| format!("component {name}"))?;
        let _ = write!(b, "\nexport const {} = {expr};\n", const_name(&name));
    }
    for (id, schema) in &bodies {
        let expr = zod_of(schema, &components, 0).with_context(|| format!("operation {id}"))?;
        let _ = write!(b, "\nexport const {id}Schema = {expr};\n");
        let _ = writeln!(
            b,
            "export type {}Input = z.infer<typeof {id}Schema>;",
            upper_first(id)
        );
    }
    Ok(Some(b))
}

/// Every schema comes after the schemas it references, because a `const` is not hoisted. Ties sort by name.
fn dependency_order(
    needed: &BTreeSet<String>,
    components: &BTreeMap<String, Schema>,
) -> Vec<String> {
    fn visit(
        name: &str,
        components: &BTreeMap<String, Schema>,
        emitted: &mut BTreeSet<String>,
        order: &mut Vec<String>,
    ) {
        if !emitted.insert(name.to_owned()) {
            return;
        }
        let mut deps = BTreeSet::new();
        if let Some(schema) = components.get(name) {
            collect(schema, components, &mut deps);
        }
        for dep in deps.iter().filter(|d| d.as_str() != name) {
            visit(dep, components, emitted, order);
        }
        order.push(name.to_owned());
    }
    let (mut emitted, mut order) = (BTreeSet::new(), Vec::new());
    for name in needed {
        visit(name, components, &mut emitted, &mut order);
    }
    order
}

fn collect(schema: &Schema, components: &BTreeMap<String, Schema>, out: &mut BTreeSet<String>) {
    if !schema.reference.is_empty() {
        if let Some(name) = ref_name(&schema.reference)
            && out.insert(name.to_owned())
            && let Some(target) = components.get(name)
        {
            collect(target, components, out);
        }
        return;
    }
    for property in schema.properties.values() {
        collect(property, components, out);
    }
    if let Some(items) = &schema.items {
        collect(items, components, out);
    }
}

fn zod_of(schema: &Schema, components: &BTreeMap<String, Schema>, depth: usize) -> Result<String> {
    if !schema.reference.is_empty() {
        let Some(name) = ref_name(&schema.reference) else {
            bail!(
                "unsupported $ref `{}`. Only #/components/schemas/<name> is understood",
                schema.reference
            );
        };
        if !components.contains_key(name) {
            bail!("$ref `{}` resolves to nothing", schema.reference);
        }
        return Ok(const_name(name));
    }
    match schema.kind.as_str() {
        "object" => zod_object(schema, components, depth),
        "array" => {
            let items = schema
                .items
                .as_deref()
                .context("an array schema has no `items`")?;
            Ok(format!("z.array({})", zod_of(items, components, depth)?))
        }
        "string" => Ok(zod_string(schema)),
        "integer" => Ok(zod_number(schema, ".int()")),
        "number" => Ok(zod_number(schema, "")),
        "boolean" => Ok("z.boolean()".to_owned()),
        "" => bail!("schema has no `type` and no `$ref`"),
        other => bail!("unsupported type `{other}`"),
    }
}

fn zod_object(
    schema: &Schema,
    components: &BTreeMap<String, Schema>,
    depth: usize,
) -> Result<String> {
    if schema.properties.is_empty() {
        return Ok("z.object({})".to_owned());
    }
    let pad = "  ".repeat(depth + 1);
    let mut b = "z.object({\n".to_owned();
    for (key, property) in &schema.properties {
        let mut expr =
            zod_of(property, components, depth + 1).with_context(|| format!("property {key}"))?;
        if !schema.required.contains(key) {
            expr.push_str(".optional()");
        }
        let _ = writeln!(b, "{pad}{}: {expr},", quote_key(key));
    }
    let _ = write!(b, "{}}})", "  ".repeat(depth));
    Ok(b)
}

fn zod_string(schema: &Schema) -> String {
    if !schema.values.is_empty() {
        let quoted: Vec<String> = schema.values.iter().map(|v| format!("\"{v}\"")).collect();
        return format!("z.enum([{}])", quoted.join(", "));
    }
    let mut out = "z.string()".to_owned();
    if schema.format == "date-time" {
        out.push_str(".datetime()");
    }
    if let Some(n) = schema.min_length {
        let _ = write!(out, ".min({n})");
    }
    if let Some(n) = schema.max_length {
        let _ = write!(out, ".max({n})");
    }
    if !schema.pattern.is_empty() {
        let _ = write!(out, ".regex(/{}/)", schema.pattern);
    }
    out
}

fn zod_number(schema: &Schema, suffix: &str) -> String {
    let mut out = format!("z.number(){suffix}");
    if let Some(n) = schema.minimum {
        let _ = write!(out, ".min({})", shortest(n));
    }
    if let Some(n) = schema.maximum {
        let _ = write!(out, ".max({})", shortest(n));
    }
    out
}

/// The shortest form of a number, with an exponent below 1e-4 and from 1e6 up. JavaScript reads it as the same value.
fn shortest(n: f64) -> String {
    let exponent = if n == 0.0 {
        0
    } else {
        format!("{n:e}")
            .split_once('e')
            .and_then(|(_, e)| e.parse::<i32>().ok())
            .unwrap_or(0)
    };
    if (-4..6).contains(&exponent) {
        return format!("{n}");
    }
    let text = format!("{n:e}");
    let (mantissa, e) = text.split_once('e').unwrap_or((&text, "0"));
    let value: i32 = e.parse().unwrap_or(0);
    let sign = if value < 0 { '-' } else { '+' };
    format!("{mantissa}e{sign}{:02}", value.abs())
}

fn ref_name(reference: &str) -> Option<&str> {
    reference.strip_prefix("#/components/schemas/")
}

fn const_name(name: &str) -> String {
    let mut chars = name.chars();
    let first = chars.next().map(|c| c.to_ascii_lowercase());
    format!(
        "{}{}Schema",
        first.map_or_else(String::new, String::from),
        chars.as_str()
    )
}

fn upper_first(name: &str) -> String {
    let mut chars = name.chars();
    let first = chars.next().map(|c| c.to_ascii_uppercase());
    format!(
        "{}{}",
        first.map_or_else(String::new, String::from),
        chars.as_str()
    )
}

/// Quotes a property name only when it is not a bare JavaScript identifier.
fn quote_key(key: &str) -> String {
    let bare = key.chars().enumerate().all(|(i, c)| {
        c == '_' || c == '$' || c.is_ascii_alphabetic() || (i > 0 && c.is_ascii_digit())
    });
    if bare {
        key.to_owned()
    } else {
        format!("\"{key}\"")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_body_and_its_components_become_a_module() {
        let spec = "paths:\n  /a:\n    post:\n      operationId: createThing\n      requestBody:\n        content:\n          application/json:\n            schema:\n              $ref: \"#/components/schemas/Thing\"\ncomponents:\n  schemas:\n    Money:\n      type: string\n      pattern: \"^[0-9]+$\"\n    Thing:\n      type: object\n      required: [price]\n      properties:\n        price:\n          $ref: \"#/components/schemas/Money\"\n        kind-of:\n          type: string\n          enum: [a, b]\n        size:\n          type: integer\n          minimum: 1\n          maximum: 1000000\n";
        let out = render("api", spec, "// {service}\n").unwrap().unwrap();
        assert_eq!(
            out,
            "// api\n\nexport const moneySchema = z.string().regex(/^[0-9]+$/);\n\nexport const thingSchema = z.object({\n  \"kind-of\": z.enum([\"a\", \"b\"]).optional(),\n  price: moneySchema,\n  size: z.number().int().min(1).max(1e+06).optional(),\n});\n\nexport const createThingSchema = thingSchema;\nexport type CreateThingInput = z.infer<typeof createThingSchema>;\n"
        );
    }

    #[test]
    fn numbers_stay_short() {
        assert_eq!(shortest(100.0), "100");
        assert_eq!(shortest(0.5), "0.5");
        assert_eq!(shortest(999_999.0), "999999");
        assert_eq!(shortest(1_000_000.0), "1e+06");
        assert_eq!(shortest(1_234_567.0), "1.234567e+06");
        assert_eq!(shortest(0.00001), "1e-05");
    }
}
