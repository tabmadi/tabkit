//! Generates the third-party image allow-list and the list of images that a local cluster warms.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::LazyLock;

use anyhow::{Context, Result, bail};
use regex::Regex;
use saphyr::MarkedYaml;
use tabkit_core::yaml;

use super::{detail, ok, step, warn};

const OUT: &str = "infra/gitops/platform/image-allowlist.yaml";
const REFS_OUT: &str = "infra/local/image-refs.txt";
const SHARED: &str = "infra/gitops/platform/shared-values.yaml";
const LOCAL_ENV: &str = "local";
const ALL_ENVS: [&str; 4] = ["local", "dev", "staging", "prod"];
const LOCAL_REGISTRY: &str = "registry.localhost:5000/";
const WORKLOADS: [&str; 7] = [
    "Deployment",
    "StatefulSet",
    "DaemonSet",
    "Job",
    "ReplicaSet",
    "Pod",
    "CronJob",
];

const ALLOWLIST_HEADER: &str = "# GENERATED by `just gen-image-allowlist`. Do not edit.
# Every image repository that the platform's charts pull from, per ADR-0113. Kyverno rejects anything else.
# A new entry is a registry this platform has never used. Repositories, not references: the digest is pinned elsewhere.
policies:
  allowedImageSources:
";

const REFS_HEADER: &str = "# GENERATED by `just gen-image-allowlist`. Do not edit.
#
# Every third-party image that a local cluster pulls, as a full reference.
# `cluster-up` warms zot with this list before it creates the cluster, per ADR-0114.
# The mirror fetches each image once, in sequence, with no pod waiting for it.
#
# The first column is the earliest tier that needs the image. Every tier warms `base`.
# Only the full tier warms `full`, because only it runs ArgoCD and what ArgoCD deploys.
# One file, not two, because the set is one decision, and a second list needs upkeep.
";

static REFERENCE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^([a-z0-9][a-z0-9._-]*(:[0-9]+)?(/[a-z0-9._/-]+)+(:[A-Za-z0-9._-]+)?(@sha256:[a-f0-9]+)?|[a-z0-9][a-z0-9._-]*:[A-Za-z0-9._-]+)$")
        .expect("the pattern compiles")
});
static CONFIG_IMAGE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^[ \t]*image:[ \t]*(\S+)").expect("the pattern compiles"));
static RAW_IMAGE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r#"(?m)^[ \t-]*image(?:Name)?:[ \t]*["']?([^\s"']+)"#).expect("the pattern compiles")
});
static CHART: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"infra/helm/platform/([a-z0-9-]+)").expect("the pattern compiles")
});

fn field<'a, 'b>(node: &'a MarkedYaml<'b>, name: &str) -> Option<&'a MarkedYaml<'b>> {
    yaml::pairs(node)
        .find(|(k, _)| yaml::string(k) == Some(name))
        .map(|(_, v)| v)
}

fn path<'a, 'b>(node: &'a MarkedYaml<'b>, keys: &[&str]) -> Option<&'a MarkedYaml<'b>> {
    keys.iter()
        .try_fold(node, |current, key| field(current, key))
}

fn push_containers(spec: &MarkedYaml<'_>, keys: &[&str], out: &mut Vec<String>) {
    for key in keys {
        for container in field(spec, key).map(yaml::items).unwrap_or_default() {
            if let Some(image) = field(container, "image").and_then(yaml::text) {
                out.push(image);
            }
        }
    }
}

fn walk(node: &MarkedYaml<'_>, out: &mut Vec<String>) {
    if let Some(image) = field(node, "imageName").and_then(yaml::text) {
        out.push(image);
    }
    if let Some(spec) = path(node, &["template", "spec"]) {
        push_containers(spec, &["containers"], out);
    }
    for child in yaml::children(node) {
        walk(child, out);
    }
}

/// The documents of a rendered stream. Each one parses alone, so one odd document cannot hide the images of the rest.
fn documents(rendered: &str) -> Vec<String> {
    let mut docs = vec![String::new()];
    for line in rendered.lines() {
        if line == "---" || line.starts_with("--- ") {
            docs.push(String::new());
        } else if let Some(last) = docs.last_mut() {
            last.push_str(line);
            last.push('\n');
        }
    }
    docs
}

fn collect_document(doc: &MarkedYaml<'_>, found: &mut Vec<String>) {
    let kind = field(doc, "kind").and_then(yaml::text).unwrap_or_default();
    if WORKLOADS.contains(&kind.as_str()) {
        let specs = [
            path(doc, &["spec", "template", "spec"]),
            path(doc, &["spec", "jobTemplate", "spec", "template", "spec"]),
            field(doc, "spec"),
        ];
        for spec in specs.into_iter().flatten() {
            push_containers(
                spec,
                &["containers", "initContainers", "ephemeralContainers"],
                found,
            );
        }
    }
    walk(doc, found);
    if kind == "ConfigMap" {
        for (key, value) in field(doc, "data").into_iter().flat_map(yaml::pairs) {
            let Some(value) = yaml::text(value) else {
                continue;
            };
            found.extend(CONFIG_IMAGE.captures_iter(&value).map(|c| c[1].to_string()));
            if yaml::text(key).is_some_and(|k| k.ends_with("_IMAGE")) {
                found.extend(value.lines().map(str::to_string));
            }
        }
    }
}

/// Every image reference in a rendered manifest stream.
fn collect(rendered: &str) -> Vec<String> {
    let mut found = Vec::new();
    for text in documents(rendered) {
        match yaml::load(&text) {
            Ok(docs) => docs
                .iter()
                .for_each(|doc| collect_document(doc, &mut found)),
            // A shorter list would reject a real pod, so a strict parser error falls back to the lines of the document.
            Err(_) => found.extend(RAW_IMAGE.captures_iter(&text).map(|c| c[1].to_string())),
        }
    }
    found.retain(|image| REFERENCE.is_match(image));
    found
}

/// The repository of a reference. A trailing `:<tag>` counts only after the last `/`, because before it a colon is a port.
fn repository(image: &str) -> &str {
    let image = image.split("@sha256:").next().unwrap_or(image);
    match image.rfind(':') {
        Some(colon) if !image[colon + 1..].contains('/') => &image[..colon],
        _ => image,
    }
}

fn render_allowlist(images: &BTreeSet<String>) -> String {
    let repositories: BTreeSet<&str> = images.iter().map(|i| repository(i)).collect();
    let mut out = ALLOWLIST_HEADER.to_string();
    for repo in repositories {
        out.push_str("    - ");
        out.push_str(repo);
        out.push('\n');
    }
    out
}

fn render_refs(local: &BTreeSet<String>, base: &BTreeSet<String>) -> String {
    let third_party = |set: &BTreeSet<String>| -> BTreeSet<String> {
        set.iter()
            .filter(|i| !i.starts_with(LOCAL_REGISTRY))
            .cloned()
            .collect()
    };
    let (local, base) = (third_party(local), third_party(base));
    let mut out = REFS_HEADER.to_string();
    for image in local.intersection(&base) {
        writeln!(out, "base {image}").expect("a string write");
    }
    for image in local.difference(&base) {
        writeln!(out, "full {image}").expect("a string write");
    }
    out
}

fn words_after(text: &str, marker: &str) -> Vec<String> {
    text.lines()
        .find_map(|line| {
            line.strip_prefix(marker)?
                .strip_suffix(')')
                .map(str::to_string)
        })
        .map(|list| list.split_whitespace().map(str::to_string).collect())
        .unwrap_or_default()
}

fn stage_body<'a>(library: &'a str, stage: &str) -> Option<&'a str> {
    let start = library.find(&format!("\nstage_{stage}()"))? + 1;
    let end = library[start..]
        .find("\n}")
        .map_or(library.len(), |offset| start + offset);
    Some(&library[start..end])
}

/// The charts that the base tier installs, read from the embedded cluster stages.
fn base_charts(entry: &str, library: &str) -> Result<BTreeSet<String>> {
    let stages = words_after(entry, "STAGES_base=(");
    if stages.is_empty() {
        bail!("cannot read STAGES_base from the cluster command");
    }
    let mut charts = BTreeSet::new();
    for stage in words_after(entry, "PRELUDE=(").iter().chain(&stages) {
        if let Some(body) = stage_body(library, stage) {
            charts.extend(CHART.captures_iter(body).map(|c| c[1].to_string()));
        }
    }
    if charts.is_empty() {
        bail!("no base-tier charts found. The stage functions changed shape");
    }
    Ok(charts)
}

fn embedded(name: &str) -> Result<String> {
    let (_, body) = crate::FILES
        .iter()
        .find(|(file, _)| *file == name)
        .with_context(|| format!("{name} is not embedded"))?;
    Ok(String::from_utf8_lossy(body).into_owned())
}

fn helm_quiet(args: &[&str]) -> Option<String> {
    let out = Command::new("helm")
        .args(args)
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    out.status
        .success()
        .then(|| String::from_utf8_lossy(&out.stdout).into_owned())
}

fn dependency_names(text: &str, versions: bool) -> Result<Vec<(String, String)>> {
    let mut out = Vec::new();
    for doc in yaml::load(text)? {
        for dep in field(&doc, "dependencies")
            .map(yaml::items)
            .unwrap_or_default()
        {
            let name = field(dep, "name").and_then(yaml::text).unwrap_or_default();
            let version = if versions {
                field(dep, "version")
                    .and_then(yaml::text)
                    .unwrap_or_default()
            } else {
                String::new()
            };
            if !name.is_empty() {
                out.push((name, version));
            }
        }
    }
    Ok(out)
}

fn deps_satisfied(dir: &Path) -> Result<bool> {
    let charts = dir.join("charts");
    let lock = dir.join("Chart.lock");
    if lock.is_file() {
        for (name, version) in dependency_names(&fs::read_to_string(&lock)?, true)? {
            if !charts.join(format!("{name}-{version}.tgz")).is_file() {
                return Ok(false);
            }
        }
        return Ok(true);
    }
    let names = dependency_names(&fs::read_to_string(dir.join("Chart.yaml"))?, false)?;
    let present: Vec<String> = fs::read_dir(&charts)
        .map(|entries| {
            entries
                .filter_map(|e| e.ok()?.file_name().into_string().ok())
                .collect()
        })
        .unwrap_or_default();
    Ok(names.iter().all(|(name, _)| {
        present
            .iter()
            .any(|file| file.starts_with(&format!("{name}-")) && file.ends_with(".tgz"))
    }))
}

fn ensure_deps(name: &str, dir: &Path) -> Result<()> {
    let chart = dir.join("Chart.yaml");
    if !chart.is_file()
        || !fs::read_to_string(&chart)?
            .lines()
            .any(|l| l.starts_with("dependencies:"))
    {
        return Ok(());
    }
    if deps_satisfied(dir)? {
        return Ok(());
    }
    let text = dir.to_string_lossy();
    if helm_quiet(&["dependency", "build", &text]).is_none()
        && helm_quiet(&["dependency", "update", &text]).is_none()
    {
        bail!("{name}: helm could not fetch the dependencies in Chart.lock");
    }
    if !deps_satisfied(dir)? {
        bail!("{name}: helm reported success and Chart.lock is still unsatisfied");
    }
    Ok(())
}

fn sorted_dirs(root: &str) -> Result<Vec<PathBuf>> {
    let mut dirs: Vec<PathBuf> = fs::read_dir(root)
        .with_context(|| format!("cannot read {root}"))?
        .filter_map(|e| e.ok().map(|entry| entry.path()))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    Ok(dirs)
}

fn compare(path: &str, want: &str) -> Result<()> {
    if fs::read_to_string(path).is_ok_and(|have| have == want) {
        return Ok(());
    }
    warn(&format!("{path} is stale. Run `just gen-image-allowlist`"));
    let tmp = std::env::temp_dir().join(format!("tabkit-allowlist-{}", std::process::id()));
    fs::write(&tmp, want)?;
    let _ = Command::new("diff")
        .arg("-u")
        .arg(path)
        .arg(&tmp)
        .stdout(Stdio::inherit())
        .status();
    let _ = fs::remove_file(&tmp);
    bail!("{path} does not match what the charts render");
}

#[derive(Default)]
struct Rendered {
    images: BTreeSet<String>,
    local: BTreeSet<String>,
    base: BTreeSet<String>,
}

fn render_all(base: &BTreeSet<String>) -> Result<Rendered> {
    let (mut images, mut local, mut base_images) =
        (BTreeSet::new(), BTreeSet::new(), BTreeSet::new());
    for dir in sorted_dirs("infra/helm/platform")? {
        let name = dir
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        ensure_deps(&name, &dir)?;
        let chart = format!("{}/", dir.display());
        for env in ALL_ENVS {
            let env_values = format!("infra/gitops/platform/{env}/values.yaml");
            if !Path::new(&env_values).is_file() {
                continue;
            }
            let rendered = helm_quiet(&[
                "template", &name, &chart, "-f", SHARED, "-f", &env_values,
                "--set-file", "seed.model=infra/auth/openfga/model.json",
                "--set-file", "policies.publicKey=infra/auth/cosign/cosign.pub",
                "--set-file", r"kratos.kratos.identitySchemas.user\.v1\.json=infra/auth/kratos/identity-schemas/user.v1.json",
                "--set-file", "oathkeeper.oathkeeper.accessRules=infra/auth/oathkeeper/access-rules.json",
            ]).unwrap_or_default();
            let found = collect(&rendered);
            images.extend(found.iter().cloned());
            if env == LOCAL_ENV {
                local.extend(found.iter().cloned());
                if base.contains(&name) {
                    base_images.extend(found);
                }
            }
        }
    }
    for manifest in ["infra/local/deps.yaml", "infra/local/mock.yaml"] {
        if let Ok(text) = fs::read_to_string(manifest) {
            let found = collect(&text);
            images.extend(found.iter().cloned());
            local.extend(found.iter().cloned());
            base_images.extend(found);
        }
    }
    let services = format!("infra/gitops/services/{LOCAL_ENV}/values");
    let mut values: Vec<PathBuf> = fs::read_dir(&services)
        .map(|entries| {
            entries
                .filter_map(|e| e.ok().map(|entry| entry.path()))
                .collect()
        })
        .unwrap_or_default();
    values.retain(|p| p.extension().is_some_and(|e| e == "yaml"));
    values.sort();
    for file in values {
        let release = file
            .file_stem()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        let file = file.to_string_lossy().into_owned();
        let rendered = helm_quiet(&[
            "template",
            &release,
            "infra/helm/service",
            "-f",
            SHARED,
            "-f",
            &file,
        ])
        .unwrap_or_default();
        images.extend(collect(&rendered));
    }
    Ok(Rendered {
        images,
        local,
        base: base_images,
    })
}

pub fn run(args: &[String]) -> Result<()> {
    let check = args.first().is_some_and(|a| a == "--check");
    step("rendering every platform chart to collect its images");
    let base = base_charts(&embedded("cluster.sh")?, &embedded("lib/cluster.sh")?)?;
    detail(&format!(
        "base tier installs: {}",
        base.iter().cloned().collect::<Vec<_>>().join(" ")
    ));

    let Rendered {
        images,
        local,
        base: base_images,
    } = render_all(&base)?;

    let allowlist = render_allowlist(&images);
    let refs = render_refs(&local, &base_images);
    if check {
        step(&format!("checking {OUT} is current"));
        compare(REFS_OUT, &refs)?;
        compare(OUT, &allowlist)?;
        ok(&format!(
            "{OUT} and {REFS_OUT} match what the charts render"
        ));
        return Ok(());
    }
    step(&format!("writing {OUT}"));
    fs::write(OUT, &allowlist).with_context(|| format!("cannot write {OUT}"))?;
    fs::write(REFS_OUT, &refs).with_context(|| format!("cannot write {REFS_OUT}"))?;
    ok(&format!(
        "{} image repositories in {OUT}",
        allowlist.matches("\n    - ").count()
    ));
    ok(&format!(
        "{} image references in {REFS_OUT}",
        refs.lines()
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .count()
    ));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn collects_each_place_that_holds_an_image() {
        let text = r#"
kind: Deployment
spec:
  template:
    spec:
      initContainers: [{ image: ghcr.io/a/init:1 }]
      containers: [{ image: "postgres:19-alpine" }]
---
kind: CronJob
spec:
  jobTemplate:
    spec:
      template:
        spec:
          containers: [{ image: quay.io/a/cron:2 }]
---
kind: Cluster
spec:
  imageName: ghcr.io/a/cnpg:3
---
kind: WorkerDeployment
spec:
  template:
    spec:
      containers: [{ image: docker.io/a/worker:4 }]
---
kind: ConfigMap
data:
  template: |
    spec:
      image: ghcr.io/a/inline:5
  SIDECAR_IMAGE: ghcr.io/a/sidecar:6
"#;
        let found: BTreeSet<String> = collect(text).into_iter().collect();
        for want in [
            "ghcr.io/a/init:1",
            "postgres:19-alpine",
            "quay.io/a/cron:2",
            "ghcr.io/a/cnpg:3",
            "docker.io/a/worker:4",
            "ghcr.io/a/inline:5",
            "ghcr.io/a/sidecar:6",
        ] {
            assert!(found.contains(want), "{want} is missing");
        }
    }

    #[test]
    fn a_description_in_a_schema_is_not_an_image() {
        let text = "kind: CustomResourceDefinition\nspec:\n  imageName: The name of an image\n";
        assert_eq!(collect(text), Vec::<String>::new());
    }

    #[test]
    fn a_document_that_a_strict_parser_rejects_keeps_its_image() {
        let text = "kind: Deployment\nspec:\n  template:\n    spec:\n      containers:\n        - name: a\n          image: openfga/openfga:v1.14.2\n          args:\n            [\n              \"run\",\n          ]\n";
        assert_eq!(collect(text), vec!["openfga/openfga:v1.14.2"]);
    }

    #[test]
    fn a_port_is_not_a_tag() {
        assert_eq!(repository("registry:5000/repo"), "registry:5000/repo");
        assert_eq!(repository("registry:5000/repo:1.0"), "registry:5000/repo");
        assert_eq!(repository("ghcr.io/a/b:1@sha256:abc"), "ghcr.io/a/b");
        assert_eq!(repository("postgres:19-alpine"), "postgres");
    }

    #[test]
    fn the_refs_split_into_tiers_and_drop_the_local_registry() {
        let local: BTreeSet<String> = ["a:1", "b:1", "registry.localhost:5000/c:1"]
            .map(String::from)
            .into();
        let base: BTreeSet<String> = ["a:1"].map(String::from).into();
        let refs = render_refs(&local, &base);
        assert!(refs.ends_with("base a:1\nfull b:1\n"));
    }

    #[test]
    fn reads_the_base_charts_from_the_stages() {
        let entry = "PRELUDE=(edge)\nSTAGES_base=(postgres)\n";
        let library = "x\nstage_edge() {\n  helm infra/helm/platform/traefik\n}\nstage_postgres() {\n  helm infra/helm/platform/postgres\n}\nstage_other() {\n  helm infra/helm/platform/grafana\n}\n";
        let charts = base_charts(entry, library).unwrap();
        assert_eq!(
            charts.into_iter().collect::<Vec<_>>(),
            vec!["postgres", "traefik"]
        );
    }
}
